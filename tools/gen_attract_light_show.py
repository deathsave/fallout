"""Generate modes/attract/shows/attract_light_show.yaml for the fallout machine.

Edit the segments below, then run from the repo root:

    python3 tools/gen_attract_light_show.py
"""
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(__file__), os.pardir, "modes", "attract", "shows", "attract_light_show.yaml")

RED, YELLOW, GREEN, WHITE = "FF0000", "FFFF00", "00FF00", "FFFFFF"
PURPLE, ORANGE, BLUE, AMBER = "8000FF", "FF5500", "00D5FF", "FFB000"
RAD_RED = "BA0000"
OFF = "off"

RADS = [f"rads{i}" for i in range(1, 11)]
CAPS = ["cap_left", "cap_center", "cap_right", "capin_left", "capin_right"]
MEDS = ["med1", "med2", "med3", "med4"]
HELMET = ["power1", "powers", "power3", "power4", "power5", "power6", "power7", "power8", "power9"]
LEFT_SLINGS = ["sling_left_top", "sling_left_bottom"]
RIGHT_SLINGS = ["sling_right_top", "sling_right_bottom"]
VLOCK = ["vlock1", "vlock2", "vlock3"]

# every light the show drives, used to blank the playfield between segments
ALL = (RADS + ["big_rad"] + CAPS + MEDS + VLOCK + ["vend1", "vedn2", "vault_boy",
       "shoot_again", "stim_left", "stim_right"] + HELMET + LEFT_SLINGS + RIGHT_SLINGS)

steps = []  # (comment, duration_ms, {light: color})


def step(ms, lights, comment=None):
    steps.append((comment, ms, dict(lights)))


def blank():
    return {name: OFF for name in ALL}


# --- 1. Geiger counter: the rad meter fills, big rad goes critical ---------
lit = blank()
for i, name in enumerate(RADS):
    lit[name] = GREEN if i < 4 else (YELLOW if i < 7 else RED)
    step(120, lit, "Geiger counter: rad meter fills" if i == 0 else None)
for n in range(4):
    step(120, {"big_rad": RED, **{r: RED for r in RADS}}, "big rad goes critical" if n == 0 else None)
    step(120, {"big_rad": OFF, **{r: OFF for r in RADS}})

# --- 2. Vault door: locks light up in turn, vault boy waves ----------------
lit = blank()
for i, name in enumerate(VLOCK):
    lit[name] = [RED, YELLOW, GREEN][i]
    step(250, lit, "Vault door: locks open" if i == 0 else None)
for n in range(3):
    step(150, {"vault_boy": BLUE}, "vault boy" if n == 0 else None)
    step(150, {"vault_boy": OFF})

# --- 3. Wasteland loot: caps chase, meds fill, stims pulse -----------------
lit = blank()
for n in range(2):
    for i, name in enumerate(CAPS):
        step(90, {**lit, **{c: (WHITE if c == name else OFF) for c in CAPS}},
             "Loot: bottle caps chase" if (n, i) == (0, 0) else None)
for i, name in enumerate(MEDS):
    lit[name] = PURPLE
    step(160, lit, "med kits fill" if i == 0 else None)
for n in range(2):
    step(150, {"stim_left": RED, "stim_right": RED}, "stims pulse" if n == 0 else None)
    step(150, {"stim_left": OFF, "stim_right": OFF})

# --- 4. Power armor helmet sweeps, slings fire left/right ------------------
lit = blank()
for i, name in enumerate(HELMET):
    lit[name] = YELLOW
    step(80, lit, "Power armor: helmet sweep" if i == 0 else None)
for n in range(4):
    step(200, {**{s: ORANGE for s in LEFT_SLINGS}, **{s: OFF for s in RIGHT_SLINGS},
               **{h: (RED if n % 2 else YELLOW) for h in HELMET}},
         "slings fire left / right" if n == 0 else None)
    step(200, {**{s: OFF for s in LEFT_SLINGS}, **{s: ORANGE for s in RIGHT_SLINGS}})

# --- 5. Nuke: everything flashes white, then a colour wave -----------------
for n in range(4):
    step(120, {name: WHITE for name in ALL}, "Nuke: full playfield flash" if n == 0 else None)
    step(120, blank())
for n, color in enumerate([RED, AMBER, YELLOW, GREEN]):
    step(400, {name: color for name in ALL}, "fallout colour wave" if n == 0 else None)

# --- 6. Rest: the normal attract colours for a moment ----------------------
step(3000, {**{r: RAD_RED for r in RADS}, **{c: WHITE for c in CAPS},
            "shoot_again": GREEN, **{m: PURPLE for m in MEDS}, "big_rad": RED,
            "stim_left": RAD_RED, "stim_right": RAD_RED, "vend1": AMBER, "vedn2": AMBER,
            "vlock1": RED, "vlock2": YELLOW, "vlock3": GREEN,
            **{h: YELLOW for h in HELMET}, "vault_boy": BLUE,
            **{s: YELLOW for s in LEFT_SLINGS + RIGHT_SLINGS}},
     "Rest: steady attract colours")

total = sum(ms for _, ms, _ in steps)
lines = ["#show_version=6", "##! show: attract_light_show",
         f"# Attract mode light show for the fallout machine (~{total / 1000:.1f}s loop).",
         "# Generated by tools/gen_attract_light_show.py - edit that and re-run.",
         "# Lights keep their colour until a later step changes them, so each step",
         "# lists only the lights that change (the first step sets every light).", ""]
state = {}
for i, (comment, ms, lights) in enumerate(steps):
    full = blank() if i == 0 else {}
    full.update(lights)
    changed = {n: c for n, c in full.items() if i == 0 or state.get(n) != c}
    state.update(full)
    if comment:
        lines.append(f"# {comment}")
    lines.append(f"- duration: {ms}ms")
    if not changed:
        continue
    lines.append("  lights:")
    for name, color in changed.items():
        lines.append(f"    {name}: {color if color == OFF else repr(color)}")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"{len(steps)} steps, {total / 1000:.1f}s")
